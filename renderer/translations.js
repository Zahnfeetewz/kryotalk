function t(key) {
  var lang = 'de';
  if (typeof currentUser !== 'undefined' && currentUser && currentUser.language) lang = currentUser.language;
  else { try { var stored = localStorage.getItem('savedLanguage'); if (stored) lang = stored; } catch(e) {} }
  var entry = TRANSLATIONS[key];
  if (!entry) return key;
  return entry[lang] || entry['de'] || key;
}

function getLocale() {
  var lang = 'de';
  if (typeof currentUser !== 'undefined' && currentUser && currentUser.language) lang = currentUser.language;
  else { try { var stored = localStorage.getItem('savedLanguage'); if (stored) lang = stored; } catch(e) {} }
  var map = { de: 'de-DE', en: 'en-US' };
  return map[lang] || 'de-DE';
}
